"""
Module Generator
Produces a zip containing a complete MasterChief addon module:
  slug/
    app.py          — Flask entry point (PROXY_BASE aware)
    plugin.py       — data fetcher using selected features
    template.html   — Jinja2 data display template
    requirements.txt
    README.md
"""
import json
import zipfile
import textwrap
from pathlib import Path
from typing import Dict, List

PACKAGE_META = {
    'psutil':      {'label': 'System Monitor',   'icon': '📊', 'color': '#00ff88'},
    'kubernetes':  {'label': 'Kubernetes',         'icon': '⎈',  'color': '#326CE5'},
    'docker':      {'label': 'Docker Manager',     'icon': '🐳', 'color': '#2496ED'},
    'boto3':       {'label': 'AWS Manager',        'icon': '☁',  'color': '#FF9900'},
    'redis':       {'label': 'Redis Explorer',     'icon': '🔴', 'color': '#DC382C'},
    'paramiko':    {'label': 'SSH Manager',        'icon': '🔐', 'color': '#f5a623'},
    'requests':    {'label': 'HTTP Client',        'icon': '🌐', 'color': '#58a6ff'},
    'sqlalchemy':  {'label': 'Database Explorer',  'icon': '🗄',  'color': '#a78bfa'},
    'celery':      {'label': 'Task Queue',         'icon': '⚙',  'color': '#37b24d'},
}


def generate_module(
    pip_name: str,
    slug: str,
    features: List[str],
    output_dir: Path,
) -> Dict:
    """
    Generate a module zip.
    Returns: {success, slug, files_created, zip_path, file_count}
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    mod_dir = output_dir / slug
    mod_dir.mkdir(exist_ok=True)

    meta = PACKAGE_META.get(pip_name, {
        'label': pip_name.replace('_', ' ').replace('-', ' ').title(),
        'icon':  '📦',
        'color': '#f5a623',
    })

    files = {
        'app.py':          _gen_app_py(pip_name, slug, meta),
        'plugin.py':       _gen_plugin_py(pip_name, slug, meta, features),
        'template.html':   _gen_template_html(pip_name, meta),
        'requirements.txt': f'{pip_name}\nflask\n',
        'README.md':       _gen_readme(pip_name, slug, meta, features),
    }

    created = []
    for fname, content in files.items():
        (mod_dir / fname).write_text(content, encoding='utf-8')
        created.append(fname)

    zip_path = output_dir / f'{slug}.zip'
    with zipfile.ZipFile(zip_path, 'w', zipfile.ZIP_DEFLATED) as zf:
        for fname in files:
            zf.write(mod_dir / fname, arcname=f'{slug}/{fname}')

    return {
        'success':       True,
        'slug':          slug,
        'files_created': created,
        'zip_path':      str(zip_path),
        'file_count':    len(files),
    }


