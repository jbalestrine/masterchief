def _gen_plugin_py(pip_name: str, slug: str, meta: Dict, features: List[str]) -> str:
    label = meta['label']
    icon  = meta['icon']
    color = meta['color']

    # Build import and data-fetch sections
    short_name = pip_name.split('.')[0]
    import_line = f'import {short_name}'

    data_sections = []
    for feat_name in features[:20]:  # cap at 20 to keep file manageable
        short = feat_name.split('.')[-1]
        data_sections.append(
            f'    # {feat_name}\n'
            f'    try:\n'
            f'        result = str({feat_name})\n'
            f'        data["{short}"] = result\n'
            f'    except Exception as e:\n'
            f'        data["{short}_error"] = str(e)\n'
        )

    data_body = '\n'.join(data_sections) if data_sections else '    pass\n'

    return f'''"""
{label} Plugin
Data fetcher — auto-generated by Module System v3
Package: {pip_name}
Selected features: {len(features)}
"""
try:
    {import_line}
    _AVAILABLE = True
except ImportError as e:
    _AVAILABLE = False
    _IMPORT_ERROR = str(e)

PLUGIN_META = {{
    "label":   "{label}",
    "icon":    "{icon}",
    "color":   "{color}",
    "package": "{pip_name}",
}}


def get_data() -> dict:
    """Fetch data from {pip_name}. Returns dict of results."""
    if not _AVAILABLE:
        return {{"error": f"Package {pip_name} not available: {{_IMPORT_ERROR}}"}}

    data = {{}}

{data_body}
    return data
'''


